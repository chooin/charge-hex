#!/usr/bin/env python3
"""Compile recovered Thumb instructions into explicit C expressions and labels.
Inputs: checked flash bytes and full_assembly's address-classification inventory.
This is a static semantic lift, not an opcode interpreter or original source.
"""
from pathlib import Path
import json,hashlib
from collections import Counter
from capstone import Cs,CS_ARCH_ARM,CS_MODE_THUMB,CS_MODE_MCLASS
from capstone.arm import ARM_OP_IMM,ARM_OP_REG,ARM_OP_MEM
HERE=Path(__file__).resolve().parent;R=HERE.parent
B=(R/'artifacts/firmware.bin').read_bytes();BASE=0x08000000
inventory_path=R/'full_assembly/instructions.json'
inventory=json.loads(inventory_path.read_text())
D=Cs(CS_ARCH_ARM,CS_MODE_THUMB|CS_MODE_MCLASS);D.detail=True
code={}
for row in inventory:
 a=int(row['address'],16);i=next(D.disasm(B[a-BASE:a-BASE+4],a,count=1))
 assert i.size==row['size'] and bytes(i.bytes).hex()==row['bytes'],row
 code[a]=i

def reg(i,r):
 n=i.reg_name(r)
 if n in ['sp','lr','pc','ip','sb','sl','fp']:return {'sp':13,'lr':14,'pc':15,'ip':12,'sb':9,'sl':10,'fp':11}[n]
 assert n.startswith('r'),n
 return int(n[1:])
def val(i,o):
 if o.type==ARM_OP_IMM:return f'0x{o.imm&0xffffffff:x}u'
 if o.type==ARM_OP_REG:return f's->r[{reg(i,o.reg)}]'
 raise ValueError((i.mnemonic,i.op_str,o.type))
def mem(i,o):
 assert o.type==ARM_OP_MEM
 m=o.mem
 base=f'0x{(i.address+4)&~3:x}u' if i.reg_name(m.base)=='pc' else f's->r[{reg(i,m.base)}]'
 if m.index:base+=f' + s->r[{reg(i,m.index)}]'
 if m.disp:base+=f' + 0x{m.disp&0xffffffff:x}u'
 return '('+base+')'
header='''/* Explicit whole-firmware CPU/bus state. NOT MCU-production firmware source.
 * All recognized Thumb instructions are compiled C, including callee bodies.
 * Bus callbacks must provide peripheral/alias/Flash-controller semantics;
 * missing bus callbacks fail explicitly instead of returning dummy success.
 */
#ifndef RECOVERED_FULL_C_MODEL_H
#define RECOVERED_FULL_C_MODEL_H
#include <stdint.h>
#include <stddef.h>
struct FwMachine;
typedef uint32_t (*FwBusRead)(void *, struct FwMachine *, uint32_t address, unsigned width);
typedef void (*FwBusWrite)(void *, struct FwMachine *, uint32_t address, unsigned width, uint32_t value);
typedef void (*FwEvent)(void *, struct FwMachine *, unsigned kind, uint32_t value);
typedef struct FwMachine {
 uint32_t r[16];
 uint32_t apsr; /* NZCV bits 31..28 */
 uint32_t pc;
 uint32_t primask;
 uint32_t stop_address;
 uint32_t fault_address;
 int32_t fault;
 uint64_t instructions;
 const uint8_t *flash;
 uint8_t *sram;
 uint32_t sram_size;
 void *user;
 FwBusRead bus_read;
 FwBusWrite bus_write;
 FwEvent event;
} FwMachine;
extern const uint8_t recovered_flash_image[65536];
/* Events: 1 DSB, 2 ISB, 3 CPS(PRIMASK), 4 MSR(MSP).
 * Run returns: 0 budget consumed, 1 stop_address reached;
 * -1 unclassified PC, -2 missing/faulting bus, -3 non-Thumb BX/POP target,
 * -4 exception return not modeled, -5 unaligned halfword/word access.
 * First memory fault is retained and later memory operations are suppressed.
 * Precise exception entry/register rollback is not modeled.
 */
void recovered_firmware_init(FwMachine *, uint8_t *sram, uint32_t sram_size);
int recovered_firmware_run(FwMachine *, uint32_t instruction_budget);
#endif
'''
(HERE/'firmware_model.h').write_text(header)
helpers='''/* Whole recovered firmware as explicit C operations and control-flow labels.
 * Generated by generate.py from full_assembly/instructions.json.
 * All BL/BX/POP PC flows use this model's own translated code, not driver stubs.
 * Image bytes are available only as data (literal pools, vector/self reads).
 * This is a host-buildable semantic model. It is not an APM32 firmware build.
 */
#include "firmware_model.h"
#define NZ 0xC0000000u
#define CV 0x30000000u
static uint32_t nz(FwMachine*s,uint32_t x){s->apsr=(s->apsr&~NZ)|(x&0x80000000u)|(x?0:0x40000000u);return x;}
static uint32_t adc(FwMachine*s,uint32_t a,uint32_t b,unsigned carry){uint64_t sum=(uint64_t)a+b+carry;uint32_t r=(uint32_t)sum;s->apsr=(s->apsr&~CV)|(sum>0xffffffffu?0x20000000u:0)|((~(a^b)&(a^r)&0x80000000u)?0x10000000u:0);return nz(s,r);}
static uint32_t sbc(FwMachine*s,uint32_t a,uint32_t b,unsigned carry){uint64_t sum=(uint64_t)a+(uint32_t)~b+carry;uint32_t r=(uint32_t)sum;s->apsr=(s->apsr&~CV)|(sum>0xffffffffu?0x20000000u:0)|(((a^b)&(a^r)&0x80000000u)?0x10000000u:0);return nz(s,r);}
static uint32_t add(FwMachine*s,uint32_t a,uint32_t b){return adc(s,a,b,0);}
static uint32_t sub(FwMachine*s,uint32_t a,uint32_t b){return sbc(s,a,b,1);}
static uint32_t lsl(FwMachine*s,uint32_t a,unsigned n){uint32_t r;if(!n)return nz(s,a);s->apsr=(s->apsr&~0x20000000u)|((n<=32&&((a>>(32-n))&1u))?0x20000000u:0);r=n<32?a<<n:0;return nz(s,r);}
static uint32_t lsr(FwMachine*s,uint32_t a,unsigned n){uint32_t r;if(!n)return nz(s,a);s->apsr=(s->apsr&~0x20000000u)|((n<=32&&((a>>(n-1))&1u))?0x20000000u:0);r=n<32?a>>n:0;return nz(s,r);}
static uint32_t asr(FwMachine*s,uint32_t a,unsigned n){uint32_t r;if(!n)return nz(s,a);s->apsr=(s->apsr&~0x20000000u)|(((a>>(n<32?n-1:31))&1u)?0x20000000u:0);r=n<32?(a>>n)|((a&0x80000000u)?(~0u<<(32-n)):0):(a&0x80000000u?~0u:0);return nz(s,r);}
static void fault(FwMachine*s,int code,uint32_t address){if(!s->fault){s->fault=code;s->fault_address=address;}}
static uint32_t read_mem(FwMachine*s,uint32_t a,unsigned n){const uint8_t*p=0;uint32_t v=0;if(s->fault)return 0;if(n>1&&(a&(n-1u))){fault(s,-5,a);return 0;}if(s->flash&&a>=0x08000000u&&a-0x08000000u<=0x10000u-n)p=s->flash+(a-0x08000000u);else if(s->sram&&a>=0x20000000u&&s->sram_size>=n&&a-0x20000000u<=s->sram_size-n)p=s->sram+(a-0x20000000u);else if(s->bus_read)return s->bus_read(s->user,s,a,n);else{fault(s,-2,a);return 0;}for(unsigned i=0;i<n;i++)v|=(uint32_t)p[i]<<(8*i);return v;}
static void write_mem(FwMachine*s,uint32_t a,unsigned n,uint32_t v){uint8_t*p=0;if(s->fault)return;if(n>1&&(a&(n-1u))){fault(s,-5,a);return;}if(s->sram&&a>=0x20000000u&&s->sram_size>=n&&a-0x20000000u<=s->sram_size-n)p=s->sram+(a-0x20000000u);else if(s->bus_write){s->bus_write(s->user,s,a,n,v);return;}else{fault(s,-2,a);return;}for(unsigned i=0;i<n;i++)p[i]=(uint8_t)(v>>(8*i));}
static int branch_exchange(FwMachine*s,uint32_t target){if(s->fault)return 0;if(target>=0xfffffff0u){fault(s,-4,target);return 0;}if(!(target&1u)){fault(s,-3,target);return 0;}s->pc=target&~1u;return 1;}
static void event(FwMachine*s,unsigned kind,uint32_t value){if(s->event)s->event(s->user,s,kind,value);}
void recovered_firmware_init(FwMachine*s,uint8_t*ram,uint32_t size){*s=(FwMachine){0};s->flash=recovered_flash_image;s->sram=ram;s->sram_size=size;s->r[13]=read_mem(s,0x08000000u,4);s->pc=read_mem(s,0x08000004u,4)&~1u;}
#define N ((s->apsr>>31)&1u)
#define Z ((s->apsr>>30)&1u)
#define C ((s->apsr>>29)&1u)
#define V ((s->apsr>>28)&1u)
#define STEP(a) do{if(s->fault)return s->fault;s->pc=(a);s->r[15]=(a)+4u;if(s->stop_address==(a))return 1;if(!budget--)return 0;++s->instructions;}while(0)
int recovered_firmware_run(FwMachine*s,uint32_t budget){
 uint32_t tmp,addr;
 goto dispatch;
dispatch:
 if(s->fault)return s->fault;
 if(s->pc==s->stop_address)return 1;
 switch(s->pc){
'''
lines=[helpers]
for a in sorted(code):lines.append(f'case 0x{a:08x}u:goto L_{a:08x};')
lines += ['default:s->fault=-1;s->fault_address=s->pc;return -1;','}']
conditions={'beq':'Z','bne':'!Z','bhs':'C','blo':'!C','bhi':'C&&!Z','bls':'!C||Z','bpl':'!N','bmi':'N','bge':'N==V','blt':'N!=V','bgt':'!Z&&N==V','ble':'Z||N!=V'}
unknown=[]
def destgoto(a):
 return f'goto L_{a:08x};' if a in code else f's->pc=0x{a:08x}u;goto dispatch;'
for a,i in sorted(code.items()):
 lines.append(f'L_{a:08x}:STEP(0x{a:08x}u); /* {i.mnemonic} {i.op_str} */')
 o=i.operands;m=i.mnemonic;following=a+i.size;st=[]
 if m in ('ldr','ldrh','ldrb','ldrsh','ldrsb'):
  n={'ldr':4,'ldrh':2,'ldrb':1,'ldrsh':2,'ldrsb':1}[m]
  x=f'read_mem(s,{mem(i,o[1])},{n})'
  if m=='ldrsh':x=f'(uint32_t)(int32_t)(int16_t)({x})'
  if m=='ldrsb':x=f'(uint32_t)(int32_t)(int8_t)({x})'
  st=[f'{val(i,o[0])}={x};']
 elif m in ('str','strh','strb'):st=[f'write_mem(s,{mem(i,o[1])},{dict(str=4,strh=2,strb=1)[m]},{val(i,o[0])});']
 elif m in ('mov','movs','uxtb','uxth','sxth','mvns','rev16'):
  x=val(i,o[1]);x={'uxtb':f'(uint8_t)({x})','uxth':f'(uint16_t)({x})','sxth':f'(uint32_t)(int32_t)(int16_t)({x})','mvns':f'nz(s,~({x}))','movs':f'nz(s,{x})','rev16':f'((({x})&0x00ff00ffu)<<8)|((({x})&0xff00ff00u)>>8)'}.get(m,x)
  if reg(i,o[0].reg)==15:st=[f's->pc=({x})&~1u;goto dispatch;'];following=None
  else:st=[f'{val(i,o[0])}={x};']
 elif m=='adr':st=[f'{val(i,o[0])}=0x{((a+4)&~3)+o[1].imm:08x}u;']
 elif m in ('adds','subs','add','sub','lsls','lsrs','asrs','muls','orrs','ands','bics','eors','adcs','sbcs','rsbs'):
  dst=val(i,o[0]);x=val(i,o[1]) if len(o)==3 else dst;y=val(i,o[2]) if len(o)==3 else val(i,o[1])
  shift_y=f'({y})&255u' if o[-1].type==ARM_OP_REG else y
  expr={'adds':f'add(s,{x},{y})','subs':f'sub(s,{x},{y})','add':f'({x})+({y})','sub':f'({x})-({y})','lsls':f'lsl(s,{x},{shift_y})','lsrs':f'lsr(s,{x},{shift_y})','asrs':f'asr(s,{x},{shift_y})','muls':f'nz(s,({x})*({y}))','orrs':f'nz(s,({x})|({y}))','ands':f'nz(s,({x})&({y}))','bics':f'nz(s,({x})&~({y}))','eors':f'nz(s,({x})^({y}))','adcs':f'adc(s,{x},{y},C)','sbcs':f'sbc(s,{x},{y},C)','rsbs':f'sub(s,{y},{x})'}[m]
  if reg(i,o[0].reg)==15:st=[f's->pc=({expr})&~1u;goto dispatch;'];following=None
  else:st=[f'{dst}={expr};']
 elif m in ('cmp','cmn'):st=[f'(void){"sub" if m=="cmp" else "add"}(s,{val(i,o[0])},{val(i,o[1])});']
 elif m=='tst':st=[f'(void)nz(s,({val(i,o[0])})&({val(i,o[1])}));']
 elif m=='b':st=[destgoto(o[0].imm)];following=None
 elif m in conditions:st=[f'if({conditions[m]}){{{destgoto(o[0].imm)}}}']
 elif m=='bl':st=[f's->r[14]=0x{a+i.size+1:08x}u;',destgoto(o[0].imm)];following=None
 elif m in ('bx','blx'):
  st=[f'tmp={val(i,o[0])};']
  if m=='blx':st.append(f's->r[14]=0x{a+i.size+1:08x}u;')
  st+=['if(!branch_exchange(s,tmp))return s->fault;goto dispatch;'];following=None
 elif m=='push':
  rr=[reg(i,z.reg) for z in o];st=[f'addr=s->r[13]-{4*len(rr)}u;']
  st += [f'write_mem(s,addr+{4*j}u,4,s->r[{r}]);' for j,r in enumerate(rr)]
  st+=['s->r[13]=addr;']
 elif m=='pop':
  rr=[reg(i,z.reg) for z in o];st=['addr=s->r[13];']
  st += [f'{"tmp" if r==15 else f"s->r[{r}]"}=read_mem(s,addr+{4*j}u,4);' for j,r in enumerate(rr)]
  st += [f's->r[13]=addr+{4*len(rr)}u;']
  if 15 in rr:st+=['if(!branch_exchange(s,tmp))return s->fault;goto dispatch;'];following=None
 elif m in ('stm','ldm'):
  base=reg(i,o[0].reg);rr=[reg(i,z.reg) for z in o[1:]];st=[f'addr=s->r[{base}];']
  if m=='stm':st += [f'write_mem(s,addr+{4*j}u,4,s->r[{r}]);' for j,r in enumerate(rr)]
  else:st += [f's->r[{r}]=read_mem(s,addr+{4*j}u,4);' for j,r in enumerate(rr)]
  if i.writeback:st += [f's->r[{base}]=addr+{4*len(rr)}u;']
 elif m in ('cpsid','cpsie'):
  assert i.op_str=='i';st=[f's->primask={1 if m=="cpsid" else 0};event(s,3,s->primask);']
 elif m=='msr':
  assert i.op_str.startswith('msp,');st=[f's->r[13]={val(i,o[1])}&~3u;event(s,4,s->r[13]);']
 elif m in ('dsb','isb'):st=[f'event(s,{1 if m=="dsb" else 2},0); /* single-thread model has no queued bus writes */']
 elif m=='nop':st=['/* no effect */']
 else:unknown.append((hex(a),m,i.op_str));st=['fault(s,-6,s->pc);return -6;']
 lines += st
 if following is not None:lines.append(destgoto(following))
lines.append('}\n')
assert not unknown,unknown
(HERE/'firmware_model.c').write_text('\n'.join(lines))
data=['/* Exact original Flash bytes as DATA for vector/literal/self reads.',' * Execution is the explicit compiled C in firmware_model.c. */','#include "firmware_model.h"','const uint8_t recovered_flash_image[65536]={']
for off in range(0,len(B),16):data.append('  '+','.join(f'0x{x:02x}' for x in B[off:off+16])+f', /* {BASE+off:08x} */')
data.append('};\n');(HERE/'firmware_data.c').write_text('\n'.join(data))
report={'firmware_sha256':hashlib.sha256(B).hexdigest(),'instruction_inventory_sha256':hashlib.sha256(inventory_path.read_bytes()).hexdigest(),'translated_instructions':len(code),'translated_bytes':sum(i.size for i in code.values()),'untranslated_mnemonics':unknown,'mnemonics':dict(Counter(i.mnemonic for i in code.values())),'internal_direct_call_sites':sum(i.mnemonic=='bl' for i in code.values()),'driver_stubs':False,'model_source_sha256':hashlib.sha256((HERE/'firmware_model.c').read_bytes()).hexdigest(),'limitations':['Includes every instruction in the supplied code classification, not proof that classification found all reachable code.','Indirect transfer to an unclassified address faults explicitly.','CPU IRQ entry/exception return and peripheral/DMA/Flash-controller behavior are not supplied; bus callbacks required.','Unaligned halfword/word accesses fault explicitly; first fault is retained, but precise exception register rollback is not modeled.','Host-buildable static semantic model, not original source or MCU-sized firmware.']}
(HERE/'coverage.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps({k:v for k,v in report.items() if k!='mnemonics'},indent=2))
